ANGULOS_EJE_ROBOT = [45.5, 90.2, 12.3, 179.9] * 4000


def procesar_coordenadas_servo_optimizado():
    """Convierte directamente los ángulos decimales a enteros."""
    return [int(angulo) for angulo in ANGULOS_EJE_ROBOT]

# Commented out IPython magic to ensure Python compatibility.
# %%timeit
# procesar_coordenadas_servo_optimizado()

tiempo_original_ms = 6.6
tiempo_optimizado_us = 412

tiempo_optimizado_ms = tiempo_optimizado_us / 1000

porcentaje_mejora = (
    (tiempo_original_ms - tiempo_optimizado_ms)
    / tiempo_original_ms
) * 100

factor_aceleracion = (
    tiempo_original_ms / tiempo_optimizado_ms
)

print(f"Tiempo original: {tiempo_original_ms} ms")
print(f"Tiempo optimizado: {tiempo_optimizado_ms} ms")
print(f"Mejora de rendimiento: {porcentaje_mejora:.2f} %")
print(f"El código optimizado es {factor_aceleracion:.2f} veces más rápido")

resultado_original = procesar_coordenadas_servo()
resultado_optimizado = procesar_coordenadas_servo_optimizado()

print("Primeros 12 resultados originales:")
print(resultado_original[:12])

print("\nPrimeros 12 resultados optimizados:")
print(resultado_optimizado[:12])

print("\n¿Los resultados son iguales?")
print(resultado_original == resultado_optimizado)

print("\nCantidad de ángulos procesados:")
print(len(resultado_optimizado))